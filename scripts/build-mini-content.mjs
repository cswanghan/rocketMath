// 把 content/*.json 打成小程序能 require 的 .js 模块。
//
// 为什么不直接 require JSON: 小程序基础库对 JSON 模块的支持随版本波动,
// 而 `module.exports = {...}` 的 .js 在任何基础库上都稳。体积差异可忽略
// (代码包按压缩后计算, JSON 压缩率 6-8 倍)。
//
// 投放策略 (见 docs/miniprogram-design.md §3):
//   主包    fluency pack + knowledge map + english practice pack (小, 多个分包要用)
//   math 分包  practice pack (大, 进知识点练习才需要)
//   lang 分包  词库 + 语文生字库
//   exam 分包  exam calendar
//
// 英语题集为什么在主包: 它只有 16KB, 但 exam 分包的备考清单和 math 分包的练习页
// 都要读它 —— 分包之间不能互相 require, 放主包是唯一能共享的位置。
//
// 用法: npm run mini:content

import { mkdirSync, readFileSync, writeFileSync, readdirSync, rmSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CONTENT = join(ROOT, 'content');
const MINI = join(ROOT, 'apps', 'mini');

const GRADES = [3, 4, 5, 6, 7, 8, 9];

/** 一份内容 → 一个 .js 模块。返回原始字节数, 用于体积报告。 */
function emit(srcFile, outFile) {
  const raw = readFileSync(join(CONTENT, srcFile), 'utf8');
  // 解析再序列化: 顺带校验 JSON 合法, 并去掉源文件的缩进空白
  const data = JSON.parse(raw);
  const body = JSON.stringify(data);
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, `// GENERATED by scripts/build-mini-content.mjs — 请勿手改\nmodule.exports = ${body};\n`);
  return body.length;
}

function clean(dir) {
  try {
    rmSync(dir, { recursive: true, force: true });
  } catch {
    /* 首次运行目录不存在 */
  }
}

const report = [];
let mainBytes = 0;
let mathBytes = 0;

clean(join(MINI, 'content'));
clean(join(MINI, 'packages', 'math', 'content'));
clean(join(MINI, 'packages', 'lang', 'content'));
clean(join(MINI, 'packages', 'exam', 'content'));

// --- 主包: 流畅度包 + 知识地图 ---------------------------------------------
for (const g of GRADES) {
  mainBytes += emit(
    `grade${g}_math_fluency_pack.json`,
    join(MINI, 'content', `grade${g}_fluency.js`),
  );
  mainBytes += emit(
    `grade${g}_knowledge_map.json`,
    join(MINI, 'content', `grade${g}_map.js`),
  );
}

// 英语练习题集 (KET/PET 语法阅读)。备考清单和练习页分属 exam / math 两个分包,
// 分包之间不能互相 require —— 放主包才能共享。
mainBytes += emit('english_practice_pack.json', join(MINI, 'content', 'english_practice.js'));

// 主包索引: 静态 require 表。小程序打包器不支持动态路径 require,
// 所以这里必须把每个年级写成字面量分支。
const mainIndex = `// GENERATED by scripts/build-mini-content.mjs — 请勿手改
// 主包内容索引。小程序打包器只认字面量路径, 故逐个静态 require。
const FLUENCY = {
${GRADES.map((g) => `  ${g}: () => require('./grade${g}_fluency.js'),`).join('\n')}
};
const MAPS = {
${GRADES.map((g) => `  ${g}: () => require('./grade${g}_map.js'),`).join('\n')}
};

module.exports = {
  GRADES: [${GRADES.join(', ')}],
  fluencyPack(grade) {
    const f = FLUENCY[grade];
    if (!f) throw new Error('不支持的年级: ' + grade);
    return f();
  },
  knowledgeMap(grade) {
    const f = MAPS[grade];
    if (!f) throw new Error('不支持的年级: ' + grade);
    return f();
  },
  englishPack() {
    return require('./english_practice.js');
  },
};
`;
writeFileSync(join(MINI, 'content', 'index.js'), mainIndex);

// --- math 分包: 练习题集 ----------------------------------------------------
for (const g of GRADES) {
  mathBytes += emit(
    `grade${g}_practice_pack.json`,
    join(MINI, 'packages', 'math', 'content', `grade${g}_practice.js`),
  );
}
const mathIndex = `// GENERATED by scripts/build-mini-content.mjs — 请勿手改
// math 分包内容索引 (练习题集, 只有进知识点练习才加载)。
const PRACTICE = {
${GRADES.map((g) => `  ${g}: () => require('./grade${g}_practice.js'),`).join('\n')}
};

module.exports = {
  practicePack(grade) {
    const f = PRACTICE[grade];
    if (!f) throw new Error('不支持的年级: ' + grade);
    return f();
  },
};
`;
writeFileSync(join(MINI, 'packages', 'math', 'content', 'index.js'), mathIndex);

// --- lang 分包: 词库 + 语文生字库 -------------------------------------------
let langBytes = 0;

// 背单词词库。源文件 public/vocab-data.js 是给浏览器用的 —— 它往 window 上挂
// VOCAB_LIBRARY, 又在顶层 const 了 EN_DEFS。这里塞一个假 window 把它跑一遍,
// 取出两份数据再序列化成 CommonJS。
//
// 为什么不手抄一份: 词库还在持续加词, 手抄必然分叉。跑源文件 = 单一数据源。
function evalBrowserGlobals(file, epilogue) {
  const src = readFileSync(file, 'utf8');
  // eslint-disable-next-line no-new-func
  return new Function('window', `${src}\n${epilogue}`)({});
}

const vocab = evalBrowserGlobals(
  join(ROOT, 'public', 'vocab-data.js'),
  'return { lib: window.VOCAB_LIBRARY, defs: typeof EN_DEFS === "undefined" ? {} : EN_DEFS };',
);
if (!vocab.lib || !Array.isArray(vocab.lib.words) || !vocab.lib.words.length) {
  throw new Error('public/vocab-data.js 没产出 VOCAB_LIBRARY.words —— 结构变了?');
}
const vocabBody = JSON.stringify({
  levels: vocab.lib.levels,
  topics: vocab.lib.topics,
  sourceLinks: vocab.lib.sourceLinks || [],
  words: vocab.lib.words,
  defs: vocab.defs,
});
mkdirSync(join(MINI, 'packages', 'lang', 'content'), { recursive: true });
writeFileSync(
  join(MINI, 'packages', 'lang', 'content', 'vocab.js'),
  `// GENERATED by scripts/build-mini-content.mjs (源: public/vocab-data.js) — 请勿手改\nmodule.exports = ${vocabBody};\n`,
);
langBytes += vocabBody.length;
console.log(
  `  · 词库 ${vocab.lib.words.length} 词 / ${vocab.lib.topics.length} 主题 / 英英释义 ${Object.keys(vocab.defs).length} 条`,
);

// 语文生字库。源数据写在两个独立 HTML 的 <script> 里 (chinese-characters.html /
// chinese-reading.html), 这里按名字把字面量整段抠出来再 eval。
//
// 抠的是「纯字面量声明」, 不跑整段脚本 —— 那段脚本一跑就要 document, 而且带
// hanzi-writer/cnchar 的 CDN 依赖, 小程序侧都没有。
function extractLiteral(src, name) {
  const m = new RegExp(`const\\s+${name}\\s*=\\s*`).exec(src);
  if (!m) throw new Error(`没找到 const ${name} —— 源文件结构变了?`);
  const start = m.index + m[0].length;
  const open = src[start];
  const close = open === '{' ? '}' : ']';
  let depth = 0;
  let quote = null;
  let escaped = false;
  for (let i = start; i < src.length; i += 1) {
    const ch = src[i];
    if (quote) {
      if (escaped) escaped = false;
      else if (ch === '\\') escaped = true;
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === '"' || ch === "'" || ch === '`') {
      quote = ch;
      continue;
    }
    if (ch === open) depth += 1;
    else if (ch === close) {
      depth -= 1;
      if (depth === 0) return src.slice(start, i + 1);
    }
  }
  throw new Error(`const ${name} 的括号没闭合`);
}

function evalLiteral(src, name) {
  // eslint-disable-next-line no-new-func
  return new Function(`return ${extractLiteral(src, name)};`)();
}

const charsHtml = readFileSync(join(ROOT, 'public', 'chinese-characters.html'), 'utf8');
const readingHtml = readFileSync(join(ROOT, 'public', 'chinese-reading.html'), 'utf8');
const chinese = {
  RAD: evalLiteral(charsHtml, 'RAD'),
  CHARS: evalLiteral(charsHtml, 'CHARS'),
  GROUPS: evalLiteral(charsHtml, 'GROUPS'),
  RAD_MAP: evalLiteral(charsHtml, 'RAD_MAP'),
  GRADE_CHARS: evalLiteral(readingHtml, 'GRADE_CHARS'),
};
if (!chinese.CHARS.length || !Object.keys(chinese.RAD).length) {
  throw new Error('语文生字库抽取为空 —— 检查 public/chinese-*.html');
}
const chineseBody = JSON.stringify(chinese);
writeFileSync(
  join(MINI, 'packages', 'lang', 'content', 'chinese.js'),
  `// GENERATED by scripts/build-mini-content.mjs (源: public/chinese-characters.html + chinese-reading.html) — 请勿手改\nmodule.exports = ${chineseBody};\n`,
);
langBytes += chineseBody.length;
console.log(
  `  · 生字 ${chinese.CHARS.length} 个 / 偏旁 ${Object.keys(chinese.RAD).length} 类 / 分级字表 ${Object.keys(chinese.GRADE_CHARS).length} 个年级`,
);

// --- exam 分包: 考试日历 ----------------------------------------------------
const examBytes = emit('exam_calendar.json', join(MINI, 'packages', 'exam', 'content', 'exam_calendar.js'));

const kb = (n) => (n / 1024).toFixed(0) + ' KB';
report.push(['主包 (fluency+map+english)', mainBytes]);
report.push(['math 分包 (practice)', mathBytes]);
report.push(['lang 分包 (词库+生字)', langBytes]);
report.push(['exam 分包 (calendar)', examBytes]);

console.log('mini content 生成完毕 (未压缩字节, 小程序按压缩后计包体):');
for (const [name, bytes] of report) console.log(`  ${name.padEnd(24)} ${kb(bytes)}`);
console.log(`  ${'合计'.padEnd(24)} ${kb(report.reduce((a, [, b]) => a + b, 0))}`);
if (mainBytes > 1.2 * 1024 * 1024) {
  console.warn('⚠️  主包内容已超 1.2MB, 考虑把部分年级挪进分包');
}
