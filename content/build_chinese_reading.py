def validate(data):
    ids = set()
    for p in data['passages']:
        assert p['id'] not in ids
        ids.add(p['id'])
        assert p['grade'] in range(1, 7) and p['text']
        for q in p['questions']:
            assert q['id'] not in ids
            ids.add(q['id'])
            assert len(q['choices']) == 4
            assert len({c['label'] for c in q['choices']}) == 4
            assert sum(c['id'] == q['answer'] for c in q['choices']) == 1
            assert q['evidence'] in p['text'] and q['explanation']
    assert all(sum(p['grade'] == g for p in data['passages']) >= 2 for g in range(1, 7))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = build()
    validate(data)
    out = ROOT / 'public/chinese-reading-data.js'
    body = '// GENERATED by content/build_chinese_reading.py; edit the generator.\nwindow.CHINESE_READING_LIBRARY = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'
    if args.check:
        if not out.exists() or out.read_text() != body:
            raise SystemExit('Chinese reading browser asset is stale; run content/build_chinese_reading.py')
    else:
        out.write_text(body)
    print(f"Chinese reading: {len(data['passages'])} passages / {sum(len(p['questions']) for p in data['passages'])} questions / grades 1–6")


if __name__ == '__main__':
    main()
