def question(pid, skill, prompt, answer, distractors, evidence, explanation, position):
    choices = list(distractors)
    choices.insert(position, answer)
    return {"id": pid, "skill": skill, "prompt": prompt,
            "choices": [{"id": chr(97 + i), "label": text} for i, text in enumerate(choices)],
            "answer": chr(97 + position), "evidence": evidence, "explanation": explanation}


